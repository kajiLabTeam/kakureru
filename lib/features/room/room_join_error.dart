/// ルーム参加に失敗した理由。
///
/// 画面側でユーザー向けの日本語メッセージへ変換して表示するため、
/// メッセージ文字列ではなく理由そのものを投げる
/// (生の例外文がそのまま画面に出るのを避ける)。
/// データを持たないのでenumをそのまま例外として使う。
enum RoomJoinError implements Exception {
  /// そのコードのルームが存在しない(打ち間違い、または削除済み)。
  notFound,

  /// コードの形式が不正(4桁の数字でない)。画面側ではボタンを無効化して
  /// いるので普段は起きないが、別の入口(ディープリンク等)が増えたときに
  /// 空のコードでRTDBを読みにいかないための最後の砦。
  invalidCode,

  /// ルームが既に終了している。終了したルームの`roomCodes/{code}`は
  /// 削除されないため、過去のコードでも参加できてしまうのを防ぐ。
  finished,

  /// サーバー時刻を取得できず、ルームが終わっているかを判定できない。
  ///
  /// 端末時計で代用すると、時計が遅れている端末が`endsAt`を過ぎた
  /// 終了済みルームに参加できてしまう。判定できないときは参加させない
  /// (PR #103のレビュー指摘)。
  serverTimeUnavailable,
}
